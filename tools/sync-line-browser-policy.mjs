import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { lineBrowserPolicy } from "../assets/line-browser-policy.mjs";
// Static string: bundlers must not recalculate Function.toString() in production.
const LINE_BROWSER_BOOTSTRAP = `(${lineBrowserPolicy.toString()})(window).enforce();`.replaceAll("<", "\\u003c");
const hash = (value) => `'sha256-${createHash("sha256").update(value).digest("base64")}'`;
await writeFile(new URL("../assets/line-browser-csp.mjs", import.meta.url),
  `// Generated by tools/sync-line-browser-policy.mjs; exact inline content only.\nexport const LINE_BROWSER_BOOTSTRAP = ${JSON.stringify(LINE_BROWSER_BOOTSTRAP)};\nexport const LINE_BROWSER_SCRIPT_CSP = ${JSON.stringify(hash(LINE_BROWSER_BOOTSTRAP))};\nexport const LINE_BROWSER_STYLE_CSP = ${JSON.stringify(hash(lineBrowserPolicy(null).css))};\n`);
